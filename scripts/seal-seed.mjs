#!/usr/bin/env node
/**
 * Seals a dashboard setup file (the same JSON shape as a backup, usually with "merge": true) so it
 * can ship inside the site without its figures being readable in the public JavaScript.
 *
 *   node scripts/seal-seed.mjs path/to/setup.json "<passcode>" > src/data/seed.sealed.ts
 *
 * The file is encrypted with AES-GCM under a key derived from the dashboard passcode (PBKDF2,
 * SHA-256). The dashboard opens it once, the first time someone unlocks with that passcode, and
 * merges it into that browser's data. Keep the plain JSON out of the repository.
 */
import { readFileSync } from "node:fs";
import { webcrypto as crypto } from "node:crypto";

const [, , file, passcode] = process.argv;
if (!file || !passcode) {
  console.error('usage: node scripts/seal-seed.mjs setup.json "<passcode>" > src/data/seed.sealed.ts');
  process.exit(1);
}

const json = JSON.parse(readFileSync(file, "utf8"));
if (json.app !== "wilson-antoine") throw new Error("Not a Wilson Antoine setup file.");
const id = json.seedId ?? "seed";
const ITERATIONS = 210_000;

const enc = new TextEncoder();
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const material = await crypto.subtle.importKey("raw", enc.encode(passcode), "PBKDF2", false, ["deriveKey"]);
const key = await crypto.subtle.deriveKey({ name: "PBKDF2", hash: "SHA-256", salt, iterations: ITERATIONS }, material, { name: "AES-GCM", length: 256 }, false, ["encrypt"]);
const data = new Uint8Array(await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, enc.encode(JSON.stringify(json))));
const b64 = (u) => Buffer.from(u).toString("base64");

process.stdout.write(`// Generated by scripts/seal-seed.mjs — encrypted setup data, opened with the dashboard passcode.
export const SEALED_SEED = {
  id: ${JSON.stringify(id)},
  iterations: ${ITERATIONS},
  salt: "${b64(salt)}",
  iv: "${b64(iv)}",
  data: "${b64(data)}",
};
`);
